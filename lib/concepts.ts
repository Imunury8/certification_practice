import type { TopicId, ExamId } from "@/lib/types";

type ConceptTableCell = string | { label: string; swatches: string[] };

export interface ConceptItem {
  // Keep term stable for saved study plans and deep links.
  term: string;
  title?: string;
  summary: string;
  details: string[];
  examTip: string;
  imageUrl?: string;
  imageAlt?: string;
  referenceImage?: { url: string; alt: string; label: string };
  exampleTables?: { caption: string; headers: string[]; rows: ConceptTableCell[][]; wide?: boolean }[];
}

export interface ConceptSection {
  topicId: TopicId;
  title?: string;
  description?: string;
  sources?: { label: string; href: string }[];
  items: ConceptItem[];
}

const design = (
  term: string,
  category: string,
  summary: string,
  intent: string,
  useCase: string,
  tip: string,
): ConceptItem => ({
  term,
  summary: `${category} 패턴. ${summary}`,
  details: [`목적: ${intent}`, `활용: ${useCase}`, `구분 포인트: ${tip}`],
  examTip: `${term}은 ${tip}라는 단서로 구분합니다.`,
});

const item = (
  term: string,
  summary: string,
  details: string[],
  examTip: string,
  imageUrl?: string,
  title?: string,
): ConceptItem => ({
  term,
  title,
  summary,
  details,
  examTip,
  imageUrl,
});

