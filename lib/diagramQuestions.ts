export const DIAGRAM_QUESTIONS: QuestionTemplate[] = diagrams.flatMap((diagram) => {
  const answerAliases = [...new Set([
    diagram.name.replace(/ Diagram$/, ""), ...diagram.koreanNames,
    ...diagram.koreanNames.map((name) => name.replace(/ 다이어그램$/, "")),
    ...(diagram.extraAliases ?? []),
  ])].filter((alias) => alias !== diagram.name);
  const variants: [Difficulty, string][] = [
    ["easy", diagram.characteristics], ["medium", diagram.notation], ["hard", diagram.scenario],
  ];
  return variants.map(([difficulty, description]) => ({
    topicId: "diagrams", keyword: diagram.name, difficulty, type: "short",
    prompt: `${difficulty === "hard" ? "다음 상황을 표현하기에 적합한" : "다음 설명에 해당하는"} 다이어그램의 이름을 쓰시오.\n${description}`,
    answer: diagram.name, answerAliases,
    explanation: `${diagram.name} (${diagram.koreanNames[0]}): ${diagram.explanation}`,
  }));
});
